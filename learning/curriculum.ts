/**
 * The syllabus: seventy mini-levels from absolute beginner to B1.
 *
 * Only the substance is written by hand here — the theme, what it is about,
 * the words, the grammar and what the learner should be able to do. Goals,
 * thresholds and activities are derived from those in learning/mini-levels.ts,
 * so a level cannot drift out of step with its own content and every level is
 * held to the same standard for its band.
 *
 * This module is the single source of truth. The seed migration that puts
 * these rows in the database is generated from it, and a test fails on drift.
 */
export interface CurriculumEntry {
  /** Learner-facing title, in German. */
  readonly theme: string;
  /** The same subject in English, phrased to sit inside a sentence. */
  readonly focus: string;
  /**
   * Which of the learner's chosen interests this level serves. Drawn from the
   * same closed set the onboarding form offers, so a learner who asked for
   * travel and food can actually be given words from those levels first.
   */
  readonly topic: string;
  readonly vocabulary: readonly string[];
  /** Slugs from GRAMMAR_LABELS; the first one leads the level. */
  readonly grammar: readonly string[];
  /**
   * Slugs from CULTURE_LABELS: the culture and pragmatics notes this level
   * teaches — du/Sie, register, politeness. Most levels teach none.
   */
  readonly culture?: readonly string[];
  /** What the learner should be able to do, as verb phrases. */
  readonly functions: readonly string[];
}

