"use client";

import { choice, control } from "@/components/ui/styles";
import { cn } from "@/lib/utils";
import {
  useDevicePreference,
  voiceEngineStore,
  type VoiceEngine,
} from "@/lib/settings/device";

/**
 * Which voice reads replies aloud, chosen per device.
 *
 * A device preference rather than a profile field, deliberately: how good the
 * built-in voice is depends entirely on the device — a phone and a desktop
 * ship different speech — and the AI voice costs money per line, so "which
 * one here" is a question each machine answers for itself. That is also why
 * there is no save button: the choice is written the moment it is made, and
 * only to this browser.
 */

const OPTIONS: ReadonlyArray<{
  value: VoiceEngine;
  label: string;
  detail: string;
}> = [
  {
    value: "ai",
    label: "AI voice",
    detail:
      "Generated by the speech model, so it sounds like a person. Needs the server; if it cannot be reached, this device's voice steps in.",
  },
  {
    value: "browser",
    label: "This device's voice",
    detail:
      "The browser's built-in speech. Instant and free, at whatever quality this device ships — the server is never asked.",
  },
];

export function VoiceSourceSetting() {
  const engine = useDevicePreference(voiceEngineStore);

  return (
    <fieldset className="flex flex-col gap-3">
      <legend className="font-display text-sm font-medium text-chalk/80">
        Where the read-aloud voice comes from
      </legend>
      <div className="flex flex-col gap-2">
        {OPTIONS.map((option) => (
          <label key={option.value} className={cn(choice, "items-start text-sm")}>
            <input
              type="radio"
              name="voiceEngine"
              value={option.value}
              checked={engine === option.value}
              onChange={() => voiceEngineStore.write(option.value)}
              className={cn(control, "mt-0.5")}
            />
            <span className="flex flex-col gap-0.5">
              <span>{option.label}</span>
              <span className="text-xs text-chalk/45">{option.detail}</span>
            </span>
          </label>
        ))}
      </div>
      <p className="text-xs text-chalk/45">
        Saved straight away, and only on this device — each of your devices can
        answer this differently.
      </p>
    </fieldset>
  );
}
